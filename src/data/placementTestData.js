export function getRecommendedTrack(resultSummary) {
  const { passedEasy, passedMedium, passedHard } = resultSummary;

  if (!passedEasy) {
    return {
      trackName: "كورس ما قبل البرمجة (Pre-Coding)",
      reason:
        "أنسب بداية للطالب لتقوية التفكير المنطقي والأساسيات بأسلوب ممتع قبل الانتقال للمسارات.",
    };
  }

  if (passedEasy && !passedMedium) {
    return {
      trackName: "المسار التأسيسي (Foundation Path)",
      reason:
        "اجتاز الطالب المستوى الأول بنجاح، ويحتاج لتأسيس مهارات الكمبيوتر والبرمجة خطوة بخطوة.",
    };
  }

  if (passedEasy && passedMedium && !passedHard) {
    return {
      trackName: "المسار التأسيسي السريع / Scratch والبرمجة",
      reason:
        "يمتلك الطالب أساساً جيداً في استخدام الكمبيوتر وجاهز للانطلاق في المشاريع البرمجية.",
    };
  }

  return {
    trackName: "المسارات التخصصية (Software Path أو Hardware & Robotics)",
    reason:
      "تفوق الطالب في المستويات الثلاثة ويمكنه اختيار مسار البرمجة والتطبيقات أو الروبوتات والهارد وير.",
  };
}